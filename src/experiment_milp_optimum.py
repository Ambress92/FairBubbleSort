"""
Experiment: Exact MILP optimum for medium n, to substantiate Conjecture 1.

For each instance generated by generate_instances() (same seed as the LP experiment),
solve the weighted-Kemeny minimisation with fairness constraint as a MILP and compute
ratio = d_Gr / d_OPT  (vs the LP relaxation, which gives an *upper bound* on this ratio).

Sizes: n in {20, 50, 100}. Instance generator: 30 random + 20 correlated + 1 reversed
(seed=42, identical to experiment_approx_ratio.py's run_part2()).

Usage:
  python experiment_milp_optimum.py run    # solve MILP, save results
  python experiment_milp_optimum.py plot   # re-plot from saved data
"""

import json
import multiprocessing as mp
import os
import sys
import time
from itertools import combinations

import numpy as np
from scipy.optimize import milp, LinearConstraint, Bounds
from scipy.sparse import coo_matrix

sys.path.insert(0, os.path.dirname(__file__))
from experiment_approx_ratio import simulate_greedy, generate_instances

RESULTS_DIR = os.path.join(os.path.dirname(__file__), "..",
                           "experiments", "approx_ratio_empirical")
RESULTS_FILE = os.path.join(RESULTS_DIR, "milp_optimum_ratios.json")


# ==================== MILP solver ====================

def solve_milp(a, n, delta_star, time_limit=60, mip_rel_gap=0.001):
    """Exact MILP for the weighted Kemeny minimisation with fairness.
    Variables x_{ij} in {0,1} for i<j: 1 iff pair (i,j) is inverted in output.
    Objective: min sum (j-i) x_{ij}
    Fairness:  D0 - 2 * alpha^T x in [-Delta*, +Delta*]
    Triangle:  x_{ik} <= x_{ij} + x_{jk}  and  x_{ij} + x_{jk} <= 1 + x_{ik}
    Returns (cost_opt, D0). cost_opt may be the best feasible found within
    time_limit, with optimality gap <= mip_rel_gap.
    """
    m = n * (n - 1) // 2
    pairs = np.array(list(combinations(range(n), 2)), dtype=np.int32)
    pi, pj = pairs[:, 0], pairs[:, 1]
    c = (pj - pi).astype(np.float64)

    a_arr = np.array(a)
    alpha = np.sign(a_arr[pj] - a_arr[pi]).astype(np.float64)
    D0 = int(np.sum(alpha))

    triples = np.array(list(combinations(range(n), 3)), dtype=np.int32)
    n_tri = len(triples)
    ii, jj, kk = triples[:, 0], triples[:, 1], triples[:, 2]
    ij = ii * n - ii * (ii + 1) // 2 + jj - ii - 1
    jk = jj * n - jj * (jj + 1) // 2 + kk - jj - 1
    ik = ii * n - ii * (ii + 1) // 2 + kk - ii - 1
    n_constraints = 2 + 2 * n_tri

    # Fairness rows (2 of them)
    f0_r = np.zeros(m, dtype=np.int32); f0_c = np.arange(m, dtype=np.int32); f0_v = -alpha
    f1_r = np.ones(m, dtype=np.int32);  f1_c = np.arange(m, dtype=np.int32); f1_v = alpha.copy()
    base = np.arange(n_tri, dtype=np.int32)
    tA_r = np.repeat(2 + 2 * base, 3); tA_c = np.column_stack([ij, jk, ik]).ravel(); tA_v = np.tile([1.0, 1.0, -1.0], n_tri)
    tB_r = np.repeat(3 + 2 * base, 3); tB_c = np.column_stack([ij, jk, ik]).ravel(); tB_v = np.tile([-1.0, -1.0, 1.0], n_tri)

    all_r = np.concatenate([f0_r, f1_r, tA_r, tB_r])
    all_c = np.concatenate([f0_c, f1_c, tA_c, tB_c])
    all_v = np.concatenate([f0_v, f1_v, tA_v, tB_v])
    A = coo_matrix((all_v, (all_r, all_c)), shape=(n_constraints, m))

    b = np.zeros(n_constraints)
    b[0] = -(D0 - delta_star) / 2.0
    b[1] = (D0 + delta_star) / 2.0
    b[2::2] = 1.0

    cons = LinearConstraint(A, -np.inf, b)
    bnds = Bounds(np.zeros(m), np.ones(m))
    integ = np.ones(m)
    res = milp(c, constraints=cons, bounds=bnds, integrality=integ,
               options={"time_limit": time_limit,
                        "mip_rel_gap": mip_rel_gap,
                        "disp": False})
    if res.success:
        return res.fun, D0
    return None, D0


def _milp_worker(a, n, delta_star, time_limit, mip_rel_gap, q):
    """Subprocess worker: solve MILP and put result on queue."""
    try:
        result = solve_milp(a, n, delta_star, time_limit, mip_rel_gap)
        q.put(result)
    except Exception as e:
        q.put(("error", str(e)))


def solve_milp_with_timeout(a, n, delta_star, hard_timeout=120,
                             time_limit=60, mip_rel_gap=0.001):
    """Run solve_milp in a subprocess with a hard wall-clock timeout.
    Returns (cost_opt, D0) or (None, D0) on timeout/error.
    """
    ctx = mp.get_context("fork")
    q = ctx.Queue()
    p = ctx.Process(target=_milp_worker,
                    args=(a, n, delta_star, time_limit, mip_rel_gap, q))
    p.start()
    p.join(hard_timeout)
    if p.is_alive():
        p.terminate()
        p.join(2)
        if p.is_alive():
            p.kill()
            p.join(1)
        return None, None
    if q.empty():
        return None, None
    res = q.get()
    if isinstance(res, tuple) and len(res) == 2 and res[0] == "error":
        return None, None
    return res


# ==================== Main ====================

def run_experiment():
    """For each instance in the LP experiment generator, compute MILP optimum."""
    configs = [
        (20,  30, 20),
        (50,  30, 20),
        (100, 30, 20),
    ]

    results = []

    for n, n_rand, n_corr in configs:
        cn2 = n * (n - 1) // 2
        parity = cn2 % 2
        instances = list(generate_instances(n, n_rand, n_corr))
        print(f"\n{'='*60}\nn={n}, {len(instances)} instances\n{'='*60}", flush=True)

        for idx, (a, itype) in enumerate(instances):
            a_arr = np.array(a)
            pairs = np.array(list(combinations(range(n), 2)), dtype=np.int32)
            D0 = int(np.sum(np.sign(a_arr[pairs[:, 1]] - a_arr[pairs[:, 0]])))
            if D0 == 0:
                continue
            abs_D0 = abs(D0)
            delta_star = parity if abs_D0 % 2 == parity else parity + 1
            if delta_star > abs_D0:
                continue

            # Greedy
            t0 = time.time()
            _, cost_gr = simulate_greedy(a, n, delta_star)
            t_gr = time.time() - t0
            if cost_gr == float("inf"):
                continue

            # MILP exact optimum, hard 120s wall-clock cap, 60s solver time_limit,
            # 0.1% rel gap tolerance.
            t0 = time.time()
            cost_opt, _ = solve_milp_with_timeout(
                a, n, delta_star,
                hard_timeout=120, time_limit=60, mip_rel_gap=0.001,
            )
            t_milp = time.time() - t0

            if cost_opt is None or cost_opt < 1e-9:
                print(f"  [{idx+1}/{len(instances)}] {itype}: MILP timeout/failed, skipping",
                      flush=True)
                continue

            ratio = cost_gr / cost_opt
            results.append({
                "n": n,
                "type": itype,
                "idx": idx,
                "D0": D0,
                "delta_star": delta_star,
                "cost_gr": int(cost_gr),
                "cost_opt": float(cost_opt),
                "ratio": float(ratio),
                "greedy_time": t_gr,
                "milp_time": t_milp,
            })
            print(f"  [{idx+1}/{len(instances)}] {itype:12s} "
                  f"|D0|={abs_D0:>4d} d_Gr={cost_gr:>6} d*={cost_opt:>7.1f} "
                  f"ratio={ratio:.4f}  ({t_milp:.2f}s)", flush=True)

    os.makedirs(RESULTS_DIR, exist_ok=True)
    with open(RESULTS_FILE, "w") as f:
        json.dump(results, f, indent=2)
    print(f"\nSaved {len(results)} results to {RESULTS_FILE}", flush=True)
    return results


# ==================== Plotting ====================

def make_plot():
    """Plot d_Gr/d_OPT (MILP) overlaid with d_Gr/d_LP for comparison."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from collections import defaultdict

    with open(RESULTS_FILE) as f:
        milp_data = json.load(f)
    lp_path = os.path.join(RESULTS_DIR, "lp_bound_ratios.json")
    with open(lp_path) as f:
        lp_data = json.load(f)

    kept_types = {"random", "correlated", "reversed"}
    by_n_milp = defaultdict(list)
    by_n_lp = defaultdict(list)
    by_n_type_milp = defaultdict(lambda: defaultdict(list))

    for r in milp_data:
        if r["type"] in kept_types:
            by_n_milp[r["n"]].append(r["ratio"])
            by_n_type_milp[r["n"]][r["type"]].append(r["ratio"])
    for r in lp_data:
        if r["type"] in kept_types:
            by_n_lp[r["n"]].append(r["ratio"])

    ns = sorted(by_n_milp.keys())
    positions = list(range(len(ns)))

    fig, ax = plt.subplots(figsize=(6, 4.5))

    # LP-bound ratios as background (dashed/light box plot)
    bp_lp = ax.boxplot([by_n_lp[n] for n in ns],
                       positions=[p - 0.18 for p in positions],
                       widths=0.3, patch_artist=True, showfliers=False)
    for patch in bp_lp["boxes"]:
        patch.set_facecolor("lightgrey")
        patch.set_alpha(0.5)
    for med in bp_lp["medians"]:
        med.set_color("dimgrey")

    # MILP-exact ratios as foreground (filled box plot)
    bp_milp = ax.boxplot([by_n_milp[n] for n in ns],
                         positions=[p + 0.18 for p in positions],
                         widths=0.3, patch_artist=True, showfliers=False)
    for patch in bp_milp["boxes"]:
        patch.set_facecolor("C0")
        patch.set_alpha(0.4)
    for med in bp_milp["medians"]:
        med.set_color("navy")

    # Scatter on top of MILP boxes by instance type
    type_markers = {"random": ("o", "C0"), "correlated": ("s", "C2"), "reversed": ("D", "C3")}
    rng = np.random.RandomState(0)
    plotted_types = set()
    for i, n in enumerate(ns):
        for itype, (marker, color) in type_markers.items():
            vals = by_n_type_milp[n].get(itype, [])
            if not vals:
                continue
            jitter = rng.normal(0, 0.06, len(vals))
            label = itype if itype not in plotted_types else None
            plotted_types.add(itype)
            ax.scatter(i + 0.18 + jitter, vals, alpha=0.6, s=25, color=color,
                       marker=marker, zorder=3, label=label)

    ax.axhline(y=2.0, color="red", linestyle="--", linewidth=1.5, label="2-approx bound")
    ax.set_xticks(positions)
    ax.set_xticklabels([str(n) for n in ns])
    ax.set_xlabel(r"$n$", fontsize=12)
    ax.set_ylabel("Approximation ratio", fontsize=12)
    ax.legend(fontsize=8, loc="upper left")
    ax.grid(True, alpha=0.3)

    # Custom legend entries for the boxes
    from matplotlib.patches import Patch
    extra_handles = [
        Patch(facecolor="lightgrey", alpha=0.5, label=r"$d_{\mathrm{Gr}}/d^{\ast}_{\mathrm{LP}}$ (LP bound)"),
        Patch(facecolor="C0", alpha=0.4, label=r"$d_{\mathrm{Gr}}/d^{\ast}$ (MILP exact)"),
    ]
    handles, _ = ax.get_legend_handles_labels()
    ax.legend(handles=extra_handles + handles, fontsize=8, loc="upper left")

    plt.tight_layout()
    for ext in ("pdf", "png"):
        path = os.path.join(RESULTS_DIR, f"fig_milp_optimum.{ext}")
        fig.savefig(path, dpi=200)
    print(f"Saved fig_milp_optimum.{{pdf,png}}")
    plt.close()


if __name__ == "__main__":
    mode = sys.argv[1] if len(sys.argv) > 1 else "run"
    if mode == "run":
        run_experiment()
        make_plot()
    elif mode == "plot":
        make_plot()
    else:
        print("Usage: python experiment_milp_optimum.py [run|plot]")
